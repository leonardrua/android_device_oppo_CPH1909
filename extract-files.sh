#!/usr/bin/env bash
# Extract the CPH1909 stock vendor files listed in proprietary-files.txt.
# Usage: extract-files.sh [/path/to/rom-dump]
set -euo pipefail

DEVICE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MANIFEST="$DEVICE_DIR/proprietary-files.txt"

if [[ -n "${ANDROID_BUILD_TOP:-}" ]]; then
    ANDROID_ROOT="$(cd "$ANDROID_BUILD_TOP" && pwd)"
elif [[ -f "$DEVICE_DIR/../../../build/envsetup.sh" ]]; then
    ANDROID_ROOT="$(cd "$DEVICE_DIR/../../.." && pwd)"
else
    echo "ANDROID_BUILD_TOP is unset. Run source build/envsetup.sh from the Android tree first." >&2
    exit 1
fi

if [[ $# -gt 1 ]]; then
    echo "Usage: $0 [/path/to/rom-dump-or-vendor-directory]" >&2
    exit 2
fi

if [[ $# -eq 1 ]]; then
    SOURCE="$(cd "$1" && pwd)"
else
    SOURCE=""
    for candidate in \
        "$ANDROID_ROOT/rom-dump" \
        "$ANDROID_ROOT/kernel/oppo/CPH1909/rom-dump" \
        "$(cd "$DEVICE_DIR/../../.." && pwd)/rom-dump"; do
        if [[ -d "$candidate/vendor" ]]; then
            SOURCE="$candidate"
            break
        fi
    done
fi

if [[ -z "$SOURCE" ]]; then
    echo "No ROM dump found. Pass its path: $0 /path/to/rom-dump" >&2
    exit 1
fi

# Accept either the dump root or its vendor/ directory.
if [[ -d "$SOURCE/vendor" ]]; then
    DUMP_ROOT="$SOURCE"
elif [[ "$(basename "$SOURCE")" == vendor ]]; then
    DUMP_ROOT="$(dirname "$SOURCE")"
else
    echo "Source must contain a vendor/ directory, or be that directory itself: $SOURCE" >&2
    exit 1
fi

if [[ ! -f "$MANIFEST" ]]; then
    echo "Missing proprietary-files.txt: $MANIFEST" >&2
    exit 1
fi

FILES=()
while IFS= read -r line || [[ -n "$line" ]]; do
    path="${line%%#*}"
    path="${path#"${path%%[![:space:]]*}"}"
    path="${path%"${path##*[![:space:]]}"}"
    [[ -z "$path" ]] && continue

    if [[ "$path" != vendor/* || "$path" == *"/../"* || "$path" == ../* ]]; then
        echo "Invalid manifest entry (expected a vendor-relative path): $path" >&2
        exit 1
    fi
    FILES+=("$path")
done < "$MANIFEST"

if [[ ${#FILES[@]} -eq 0 ]]; then
    echo "No files listed in $MANIFEST" >&2
    exit 1
fi

MISSING=()
for path in "${FILES[@]}"; do
    [[ -f "$DUMP_ROOT/$path" ]] || MISSING+=("$path")
done

if [[ ${#MISSING[@]} -gt 0 ]]; then
    echo "These manifest files are missing from $DUMP_ROOT:" >&2
    printf '  %s\n' "${MISSING[@]}" >&2
    exit 1
fi

VENDOR_ROOT="$ANDROID_ROOT/vendor/oppo/CPH1909"
PROPRIETARY_ROOT="$VENDOR_ROOT/proprietary"
mkdir -p "$PROPRIETARY_ROOT"

for path in "${FILES[@]}"; do
    destination="$PROPRIETARY_ROOT/$path"
    mkdir -p "$(dirname "$destination")"
    cp -p "$DUMP_ROOT/$path" "$destination"
done

TEMP_MK="$(mktemp "$VENDOR_ROOT/.CPH1909-vendor.mk.XXXXXX")"
trap 'rm -f "$TEMP_MK"' EXIT
{
    cat <<'EOF'
# Generated by device/oppo/CPH1909/extract-files.sh. Do not edit.
PRODUCT_COPY_FILES += \
EOF
    last_index=$((${#FILES[@]} - 1))
    for index in "${!FILES[@]}"; do
        path="${FILES[$index]}"
        source="vendor/oppo/CPH1909/proprietary/$path"
        destination="\$(TARGET_COPY_OUT_VENDOR)/${path#vendor/}"
        if [[ "$index" -lt "$last_index" ]]; then
            printf '    %s:%s \\\n' "$source" "$destination"
        else
            printf '    %s:%s\n' "$source" "$destination"
        fi
    done
} > "$TEMP_MK"

mv "$TEMP_MK" "$VENDOR_ROOT/CPH1909-vendor.mk"
trap - EXIT
echo "Extracted ${#FILES[@]} vendor files into $PROPRIETARY_ROOT"
echo "Generated $VENDOR_ROOT/CPH1909-vendor.mk"
